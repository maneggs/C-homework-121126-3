#include <iostream>
#include <clocale>

int main() {
    setlocale(LC_ALL, "Russian");

    int a, b, c;

    std::cout << "Введите три оценки: ";
    std::cin >> a >> b >> c;

    std::cout << "Средний балл (целочисленный): " << (a + b + c) / 3 << std::endl;
    std::cout << "Средний балл (точный): " << (a + b + c) / 3.0 << std::endl;

    /*
    * ОБЪЯСНЕНИЕ РАЗНИЦЫ:
    * 1. В выражении (a + b + c) / 3 оба операнда имеют целый тип (int).
    *    В C++ деление целого числа на целое выполняется нацело: дробная часть
    *    просто отбрасывается (не округляется). Например, 13 / 3 даёт 4.
    * 2. В выражении (a + b + c) / 3.0 делитель 3.0 является числом с плавающей
    *    точкой (тип double). Компилятор автоматически приводит сумму (a + b + c)
    *    к типу double и выполняет точное деление с сохранением дробной части (4.33333).
    */

    return 0;
}
